  CONSTRAINT "ck_ra_partial" CHECK (status <> 'PARTIAL' OR (prediction_status IS NOT NULL AND prediction_status IN ('NOT_TARGET','OUT_OF_AREA','NO_ACTIVE_VERSION'))),
  CONSTRAINT "ck_ra_missing_is_failure" CHECK (prediction_status IS NULL OR prediction_status <> 'MISSING_ROW' OR status = 'FAILED'),
  CONSTRAINT "ck_ra_notify" CHECK (notify_decision IS NULL OR notify_decision IN ('SEND','SUPPRESSED_NIGHT','SUPPRESSED_SETTING','NONE')),
  CONSTRAINT "ck_ra_rule_ref_required" CHECK (status NOT IN ('SUCCEEDED','PARTIAL') OR zone_rule_set IS NOT NULL),
  CONSTRAINT "ck_ra_model_ref_required" CHECK (status <> 'SUCCEEDED' OR prediction_status <> 'OK' OR prediction_version_id IS NOT NULL),
  CONSTRAINT "ck_ra_level1_iff_skipped" CHECK (status <> 'SUCCEEDED' OR ((level = 1) = (prediction_status = 'SKIPPED'))),
  CONSTRAINT "ck_ra_weekday" CHECK (weekday IS NULL OR weekday BETWEEN 1 AND 7),
  CONSTRAINT "ck_ra_weekday_actual" CHECK (weekday_actual IS NULL OR weekday_actual BETWEEN 1 AND 7),
  CONSTRAINT "ck_ra_slot" CHECK (time_slot IS NULL OR time_slot BETWEEN 0 AND 7),
  CONSTRAINT "ck_ra_attempt" CHECK (attempt_count BETWEEN 1 AND 2)
