  "delivered_at" timestamptz,
  "delivery_failure" varchar(30),
  "error_code" varchar(100),
  "evaluated_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_ra_status" CHECK (status IS NOT NULL AND status IN ('SUCCEEDED','PARTIAL','FAILED')),
  CONSTRAINT "ck_ra_level" CHECK ((status = 'SUCCEEDED' AND level IS NOT NULL AND level IN (1,2,3)) OR (status IN ('PARTIAL','FAILED') AND level IS NULL)),
  CONSTRAINT "ck_ra_notify_only_success" CHECK (status = 'SUCCEEDED' OR notify_decision IS NULL OR notify_decision = 'NONE'),
  CONSTRAINT "ck_ra_pred_status" CHECK (prediction_status IS NULL OR prediction_status IN ('OK','SKIPPED','NOT_TARGET','OUT_OF_AREA','NO_ACTIVE_VERSION','MISSING_ROW')),
