  "event_group_count" integer,
  "report_count_radius_m" integer,
  "report_period_start" date,
  "report_period_end" date,
  "predicted_count" float8,
  "top_percent" float8,
  "reference_fine_amount" integer,
  "notify_decision" varchar(30),
  "message_title" varchar(200),
